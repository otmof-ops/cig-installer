//! Compiled-in pins (section 7.1, level `pinned`).
//!
//! `cargo xtask pins <manifest.toml>` writes `PINS` from every build in a manifest the maintainer
//! has reviewed. Empty until then: a build that is not listed here can still be `checksummed` or
//! `attested`, it just cannot be `pinned`.

/// `("tool-version-target", "sha256")`, sorted. Example key: `cig-1.20.0-linux-x86_64`.
pub const PINS: &[(&str, &str)] = &[];

/// The only owner whose attestations count (passed to `gh attestation verify --owner`).
pub const ATTEST_OWNER: &str = "otmof-ops";

/// The repositories an attestation may name: the product repositories and the installer itself.
pub const ATTEST_REPOS: &[&str] = &[
    "otmof-ops/cig-script",
    "otmof-ops/cig-orchestrator",
    "otmof-ops/cig-compile",
    "otmof-ops/cigar-script",
    "otmof-ops/cig-installer",
];

/// Is `repo` (`owner/name`) one the installer will accept an attestation from?
pub fn attest_repo_allowed(repo: &str) -> bool {
    ATTEST_REPOS.contains(&repo)
}

/// The key a pin is looked up by.
pub fn key(tool: &str, version: &str, target: &str) -> String {
    format!("{tool}-{version}-{target}")
}

/// Text of a `pins.rs` for `xtask pins`; keeps the file format in one place. `entries` are
/// `(key, sha256)`; the output is sorted and deduplicated.
pub fn render(entries: &[(String, String)]) -> String {
    let mut e: Vec<&(String, String)> = entries.iter().collect();
    e.sort();
    e.dedup();
    let mut out = String::new();
    out.push_str(
        "// SPDX-FileCopyrightText: 2026 Jay Taylor (https://github.com/otmof-ops/cig-installer)\n",
    );
    out.push_str("// SPDX-License-Identifier: Apache-2.0\n");
    out.push_str("//! Generated by `cargo xtask pins`. Do not edit by hand.\n\n");
    out.push_str("pub const PINS: &[(&str, &str)] = &[\n");
    for (k, v) in e {
        out.push_str(&format!("    (\"{k}\", \"{v}\"),\n"));
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn render_is_sorted_and_stable() {
        let a = render(&[
            ("b-1.0.0-x".into(), "22".into()),
            ("a-1.0.0-x".into(), "11".into()),
            ("a-1.0.0-x".into(), "11".into()),
        ]);
        assert!(a.find("a-1.0.0-x").unwrap() < a.find("b-1.0.0-x").unwrap());
        assert_eq!(a.matches("a-1.0.0-x").count(), 1);
        assert!(a.starts_with("// SPDX-FileCopyrightText"));
    }
    #[test]
    fn pins_are_sorted() {
        assert!(PINS.windows(2).all(|w| w[0].0 < w[1].0));
    }
}

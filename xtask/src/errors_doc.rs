//! `cargo xtask errors-doc`: `docs/ERRORS.md` from `errors/registry.toml`, never by hand. The
//! registry is read through `cigi_ui::registry`, the same reader `ciginstaller explain` uses, so
//! the page and the binary cannot disagree. A test fails when the file on disk is stale.

use std::fmt::Write as _;

use cigi_ui::registry::{number, Code, Registry};

/// The page for `reg`: ranges, the four kinds of no, then every code with its meaning, fix and
/// ranked causes, range by range.
pub fn render(reg: &Registry) -> String {
    let mut o = String::new();
    o.push_str(HEADER);

    o.push_str("\n## Ranges\n\n| codes | family | rendered as | meaning |\n|---|---|---|---|\n");
    for r in &reg.ranges {
        let _ = writeln!(
            o,
            "| `{}`–`{}` | {} | `{}` | {} |",
            r.from,
            r.to,
            r.family,
            r.kind.as_str(),
            cell(&r.meaning)
        );
    }

    o.push_str("\n## The four kinds of no\n\n| id | what you hear | whose problem | the manual's name |\n|---|---|---|---|\n");
    for n in &reg.nos {
        let _ = writeln!(
            o,
            "| `{}` | {} | {} | {} |",
            n.id,
            cell(&n.hear),
            cell(&n.whose),
            cell(&n.manual)
        );
    }

    for r in &reg.ranges {
        let members: Vec<&Code> = reg
            .codes
            .iter()
            .filter(|c| number(&c.code).is_some_and(|n| r.holds(n)))
            .collect();
        let _ = write!(
            o,
            "\n## {} (`{}`–`{}`)\n\n{}.\n\n",
            r.family,
            r.from,
            r.to,
            r.meaning.trim_end_matches('.')
        );
        if members.is_empty() {
            o.push_str("*Reserved; nothing emitted yet.*\n");
            continue;
        }
        o.push_str("| code | title | kind of no | what to type next |\n|---|---|---|---|\n");
        for c in &members {
            let _ = writeln!(
                o,
                "| [`{}`](#{}) | {}{} | {} | {} |",
                c.code,
                anchor(c),
                cell(&c.title),
                badge(c),
                cell(&hear(reg, c)),
                cell(&c.fix)
            );
        }
        for c in &members {
            code_section(&mut o, reg, c);
        }
    }
    while o.ends_with("\n\n") {
        o.pop();
    }
    o
}

const HEADER: &str = "\
<!-- SPDX-FileCopyrightText: 2026 Jay Taylor (https://github.com/otmof-ops/cig-installer) -->
<!-- SPDX-License-Identifier: CC-BY-4.0 -->
# Error codes

Every error `ciginstaller` prints carries a stable code, rendered as `error[E1811 installer]: ...`, and every code is an entry in one registry (`errors/registry.toml`): its family, which of the **four kinds of no** it is, what it means, what to type next, and its ranked causes, each with the read-only probe the doctor uses to confirm it and the remedy. `ciginstaller explain <code>` prints the same page at the terminal, and `ciginstaller explain` with no code lists them all. The installer's codes are `E1800` to `E1899`; the other products' codes are in their own references.

A code never changes meaning. A retired code is never reused. A code marked *planned* is reported by another tool, once that tool calls the installer's check. This page is generated by `cargo xtask errors-doc`; do not edit it by hand. A test fails when it is out of date.
";

fn code_section(o: &mut String, reg: &Registry, c: &Code) {
    let kind = c.kind().map_or("usage", |k| k.as_str());
    let mut meta = format!("{kind} · since {}", c.since);
    if !c.arises.is_empty() {
        let _ = write!(meta, " · arises in {}", c.arises.join(", "));
    }
    if c.has_tag("planned") {
        meta.push_str(" · planned");
    }
    if c.has_tag("compiler") {
        meta.push_str(" · from cigcompile");
    }
    if c.retired {
        meta.push_str(" · retired");
    }
    if !o.ends_with("\n\n") {
        o.push('\n');
    }
    let _ = write!(o, "### {} {}\n\n*{meta}*\n\n", c.code, c.title);
    if let Some(n) = c.no_entry() {
        let _ = write!(
            o,
            "**Kind of no:** {} ({}; {}).\n\n",
            n.hear, n.whose, n.manual
        );
    }
    let _ = write!(o, "{}\n\n**What to type next:** {}\n\n", c.meaning, c.fix);
    if !c.causes.is_empty() {
        o.push_str("**Known causes**, ranked; the doctor checks them in this order:\n\n");
        for (i, cause) in c.causes.iter().enumerate() {
            let probe = if cause.probe == "none" {
                "no probe; a suggestion, not a finding".to_string()
            } else {
                format!("probe `{}`", cause.probe)
            };
            let mut extra = Vec::new();
            if cause.fixable {
                extra.push("the doctor can apply it with a yes");
            }
            if cause.needs_burn {
                extra.push("needs a burn");
            }
            if !cause.reversible {
                extra.push("not reversible");
            }
            let tail = if extra.is_empty() {
                String::new()
            } else {
                format!(" *({})*", extra.join("; "))
            };
            let _ = writeln!(
                o,
                "{}. {} ({probe}). **Remedy:** {}{tail}",
                i + 1,
                cause.why,
                cause.remedy
            );
        }
        o.push('\n');
    }
    if !c.related.is_empty() {
        let list: Vec<String> = c
            .related
            .iter()
            .map(|r| match reg.codes.iter().find(|x| &x.code == r) {
                Some(x) => format!("[`{r}`](#{})", anchor(x)),
                None => format!("`{r}`"),
            })
            .collect();
        let _ = write!(o, "Related: {}.\n\n", list.join(", "));
    }
}

fn hear(reg: &Registry, c: &Code) -> String {
    reg.nos
        .iter()
        .find(|n| n.id == c.no)
        .map_or_else(|| c.no.clone(), |n| n.hear.clone())
}

fn badge(c: &Code) -> &'static str {
    if c.has_tag("planned") {
        " *(planned)*"
    } else {
        ""
    }
}

/// A table cell: a pipe would end it.
fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

/// The anchor GitHub gives the heading `### E1811 no such carton`.
fn anchor(c: &Code) -> String {
    format!("{} {}", c.code, c.title)
        .chars()
        .filter_map(|ch| match ch {
            ' ' | '-' => Some('-'),
            '_' => Some('_'),
            ch if ch.is_alphanumeric() => Some(ch.to_ascii_lowercase()),
            _ => None,
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    fn doc_path() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../docs/ERRORS.md")
    }

    #[test]
    fn errors_doc_is_not_stale() {
        let want = render(cigi_ui::registry::registry());
        let have = std::fs::read_to_string(doc_path()).unwrap_or_default();
        assert!(
            have == want,
            "docs/ERRORS.md is out of date with errors/registry.toml; run `cargo xtask errors-doc` and commit the result"
        );
    }

    #[test]
    fn every_code_has_a_section_and_a_row() {
        let reg = cigi_ui::registry::registry();
        assert!(!reg.codes.is_empty(), "the registry did not parse");
        let page = render(reg);
        for c in &reg.codes {
            assert!(
                page.contains(&format!("\n### {} {}\n", c.code, c.title)),
                "no section for {}",
                c.code
            );
            assert!(
                page.contains(&format!("| [`{}`](#{})", c.code, anchor(c))),
                "no row for {}",
                c.code
            );
        }
    }

    #[test]
    fn anchors_are_unique() {
        let reg = cigi_ui::registry::registry();
        let mut seen = std::collections::BTreeSet::new();
        for c in &reg.codes {
            assert!(
                seen.insert(anchor(c)),
                "two codes share the anchor of {}",
                c.code
            );
        }
    }

    #[test]
    fn anchor_follows_github() {
        let c = Code {
            code: "E1".into(),
            title: "yanked version, or carton: in use".into(),
            meaning: String::new(),
            fix: String::new(),
            no: "none".into(),
            arises: vec![],
            tags: vec![],
            since: "0.1.0".into(),
            retired: false,
            related: vec![],
            causes: vec![],
        };
        assert_eq!(anchor(&c), "e1-yanked-version-or-carton-in-use");
    }
}
